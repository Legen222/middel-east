#!/usr/bin/env node
/**
 * Writes ART-BRIEFS-CHATGPT.md (repo root): every image brief of art/manifest.json as one document that
 * ChatGPT can read and work through, with the style, the rules, each kind's format and a checklist.
 *
 *   npm run art:brief
 *
 * Status per asset: art/picked/<id>.webp → in the site; art/incoming/<id>.png|webp → delivered, waiting for review.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ART = join(dirname(fileURLToPath(import.meta.url)), '..', 'art');
const OUT = join(ART, '..', '..', '..', 'ART-BRIEFS-CHATGPT.md');
const m = JSON.parse(readFileSync(join(ART, 'manifest.json'), 'utf8'));

const BATCHES = ['style-test', 'crates', 'tiles', 'banners', 'items', 'avatars', 'illustrations'];
const USE = {
  crate: 'crate cards, the crate-opening reel, Case Battle and the odds tables, shown from about 60 to 300 px',
  tile: 'game cards in the lobby and the Games menu, about 220 × 300 px, game title laid over the top',
  banner: 'lobby hero, lobby slider and the link preview, wide, a headline laid over the left side',
  item: 'item pictures in the battle reels, drop tiles and odds tables, about 40 to 100 px; the site draws the rarity colour around them',
  backdrop: 'page background behind everything, dimmed further by the site',
  avatar: 'player pictures in chat, battles and the leaderboard, 30 to 64 px, cropped to a circle',
  illustration: 'empty states and reward cards, about 120 to 200 px',
};
const CANVAS = { '1024x1024': 'square 1024 × 1024', '1024x1536': 'portrait 1024 × 1536', '1536x1024': 'landscape 1536 × 1024' };

const state = (id) => (existsSync(join(ART, 'picked', `${id}.webp`)) ? 'done'
  : ['png', 'webp'].some((x) => existsSync(join(ART, 'incoming', `${id}.${x}`))) ? 'delivered' : 'open');
const count = (s) => m.assets.filter((a) => state(a.id) === s).length;
const box = (s) => (s === 'done' ? '[x]' : '[ ]');
const tag = (s) => (s === 'done' ? ' · ✅ in the site' : s === 'delivered' ? ' · 📥 delivered, waiting for review' : '');

const kindsUsed = [...new Set(m.assets.map((a) => a.kind))];
const kindSection = kindsUsed.map((k) => {
  const s = m.kinds[k].settings;
  return `### ${k} · ${CANVAS[s.size] ?? s.size} · ${s.background === 'transparent' ? '**transparent background**' : 'full background'}

- **Used for:** ${USE[k] ?? '–'}.
- **Kind rules:** ${m.kinds[k].style}`;
}).join('\n\n');

const assetSection = BATCHES.map((b) => {
  const list = m.assets.filter((a) => a.batch === b);
  if (!list.length) return '';
  const head = b === 'style-test' ? ' · do these first, then wait for the owner\'s approval' : '';
  return `### Batch \`${b}\` (${list.length})${head}

${list.map((a) => { const s = state(a.id); return `- ${box(s)} \`${a.id}\` · ${a.kind} · ${a.for}${tag(s)}  \n  ${a.prompt}`; }).join('\n')}`;
}).filter(Boolean).join('\n\n');

const md = `# Image briefs for ChatGPT

> Written by \`npm run art:brief\` (in \`platform/web\`) from \`platform/web/art/manifest.json\`. Do not edit this file by hand: change the manifest and run the command again.

**Status:** ${count('done')} of ${m.assets.length} images in the site · ${count('delivered')} delivered and waiting for review · ${count('open')} open.

## 1 · What this is

SCRAPLINE (working name) is a play-money demo of a gambling site set in a post-apocalyptic world built from scrap: crates, raids, scrapyards, workbenches. Players are 18+. The site is dark graphite with cyan, violet and brass accents. Most pictures are still thin line drawings; the images below replace them.

Screenshots of the current site (\`platform/web/art/reference/reference-*.png\`) show the colours and the mood to match. The thin line drawings in them are what your images replace.

| Who | Does what |
|---|---|
| **You (ChatGPT)** | Draw the images, one per brief, and keep the style consistent across all of them. |
| **Claude** (the developer) | Wrote these briefs. Reviews every image, cuts and compresses it and builds it into the site. |
| **The owner** | Approves the style test and passes files between you and Claude. |

## 2 · How to work

1. **Style test first.** Draw the ${m.assets.filter((a) => a.batch === 'style-test').length} images of batch \`style-test\` and show them to the owner. Go on only once the owner approves the look. If they want changes, adjust and redo the style test.
2. **Then batch by batch**, in this order: ${BATCHES.slice(1).map((b) => `\`${b}\``).join(', ')}.
3. **The prompt for each image** is the style (§ 3) + the rules of its kind (§ 5) + its motif (§ 6). Every image of one kind matches the approved style test: same camera angle, same light, same materials.
4. **One image per asset.** Check it against the rules (§ 4) before handing it over; redo it if it breaks one.
5. **Canvas:** square 1024 × 1024, portrait 1024 × 1536 or landscape 1536 × 1024, as its kind says.
6. **Transparent background** where the kind says so: a real transparent PNG (alpha channel). Not white, not black and not a checkerboard pattern painted into the picture.

**Delivery**
- File name: exactly the asset id plus \`.png\`, for example \`crate-barrel.png\`.
- If you can write to the repository \`legen222/middel-east\`: put the files in \`platform/web/art/incoming/\` on a new branch \`art/<batch>\` and open a pull request. Change nothing else.
- Otherwise: hand the owner the files with exactly these names, one batch at a time. The owner passes them on to Claude.
- Claude ticks an asset off below once its image is in the site.

## 3 · Style (every image)

${m.style}

**Palette:** graphite #0A0C0F and #111419, cyan #3DDCFF, violet #9B7BFF, brass #D9B467, green #3EE89A, red #FF5C6C (warnings only).

## 4 · Rules (never break them)

- **No writing anywhere:** no text, letters, numbers or signs that look like writing, no watermarks, no signatures.
- **No logos, brands or trademarks:** nothing from Rust, Facepunch, Steam, Valve, any casino or skin-trading site, any weapon maker.
- **Nothing copied:** no icons or item designs from existing games, no Steam workshop skins, no art from other gambling sites. Our own designs only.
- **No Red Cross emblem** (a red cross, especially on white). Medical things are mint green with a white plus.
- **No real people and no visible faces.** Nobody who looks under 25. Nothing cute, childish or cartoonish: gambling images must not appeal to minors.
- **No real money:** no banknotes, coins of real currencies, casino chips, slot machines or piles of cash. The site's currency is Scrap: pieces of scrap metal and brass nuts.
- **No blood, no gore, nobody hurt.** Weapons are objects only, never aimed at the viewer.
- **\`ill-break\` stays calm:** it goes on the responsible-gambling pages, so no winning, no crates opening, no rewards.

## 5 · Kinds

${kindSection}

## 6 · Assets (${m.assets.length})

${assetSection}
`;

writeFileSync(OUT, md);
console.log(`ART-BRIEFS-CHATGPT.md: ${m.assets.length} assets, ${count('done')} done, ${count('delivered')} delivered`);
